#!/usr/bin/env python3
"""Rebuild the bundled ha_mcp_tools component from one upstream ha-mcp tag.

Usage (from the repo root):

    uv run --no-project --python 3.13 fork/build.py --tag v8.7.0 --ha 2026.9.4 --rev 1 [--zip]
        [--cooldown-days 7] [--no-patches]

Steps, each fatal on failure:

1. Check out homeassistant-ai/ha-mcp at --tag (with its skills submodule) in
   fork/.cache/ha-mcp.
2. Replace custom_components/ha_mcp_tools with that tag's copy, then apply
   fork/patches/*.patch in order.
3. Build the ha-mcp wheel from the same checkout, download PyPI's wheel for
   that version, check PyPI's sha256, and require the two to hold identical
   files (so what upstream published is what the tag says).
4. Unpack the built wheel into custom_components/ha_mcp_tools/vendor/.
5. Resolve every requirement to an exact version against Home Assistant --ha's
   own constraints for aarch64 musl / Python 3.14, and pin the ones Home
   Assistant does not already ship into manifest.json (also fork/requirements.lock).
   Releases younger than --cooldown-days are ignored (Home Assistant itself is
   exempt), so a freshly hijacked package version cannot be picked up.
6. Set the manifest version to <component version>.<rev> and write
   fork/UPSTREAM.json.
7. With --zip, write dist/ha_mcp_tools.zip (the HACS release asset) and print
   its sha256.

Nothing here talks to Home Assistant or GitHub releases.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FORK = ROOT / "fork"
CACHE = FORK / ".cache"
UPSTREAM_GIT = "https://github.com/homeassistant-ai/ha-mcp.git"
COMPONENT = ROOT / "custom_components" / "ha_mcp_tools"
VENDOR = COMPONENT / "vendor"
PY_VERSION = "3.14.2"
PLATFORM = "aarch64-unknown-linux-musl"


def run(*args: str, cwd: Path | None = None, capture: bool = False) -> str:
    print("+", " ".join(args), flush=True)
    res = subprocess.run(args, cwd=cwd, check=True, text=True, capture_output=capture)
    return res.stdout if capture else ""


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=60) as resp:
        return resp.read()


def checkout(tag: str) -> Path:
    src = CACHE / "ha-mcp"
    if not (src / ".git").exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        run("git", "clone", "-q", "--filter=blob:none", UPSTREAM_GIT, str(src))
    run("git", "fetch", "--tags", "--force", "origin", cwd=src)
    run("git", "checkout", "--force", "--detach", f"refs/tags/{tag}", cwd=src)
    run("git", "clean", "-fdx", cwd=src)
    run("git", "submodule", "update", "-q", "--init", "--force", cwd=src)
    return src


def copy_component(src: Path, patches: bool) -> None:
    if COMPONENT.exists():
        shutil.rmtree(COMPONENT)
    shutil.copytree(src / "custom_components" / "ha_mcp_tools", COMPONENT,
                    ignore=shutil.ignore_patterns("__pycache__"))
    for patch in sorted((FORK / "patches").glob("*.patch")) if patches else []:
        run("git", "apply", "--whitespace=nowarn", str(patch), cwd=ROOT)


def wheel_files(path: Path) -> dict[str, str]:
    with zipfile.ZipFile(path) as zf:
        return {n: hashlib.sha256(zf.read(n)).hexdigest()
                for n in zf.namelist() if not n.endswith("/")}


def build_and_compare(src: Path, version: str, work: Path) -> tuple[Path, str, str]:
    run("uv", "build", "--wheel", "-o", str(work / "built"), cwd=src)
    built = next((work / "built").glob(f"ha_mcp-{version}-*.whl"))
    meta = json.loads(fetch(f"https://pypi.org/pypi/ha-mcp/{version}/json"))
    wheel = next(u for u in meta["urls"] if u["packagetype"] == "bdist_wheel")
    data = fetch(wheel["url"])
    digest = hashlib.sha256(data).hexdigest()
    if digest != wheel["digests"]["sha256"]:
        sys.exit(f"PyPI wheel sha256 {digest} does not match PyPI's own digest")
    pypi = work / wheel["filename"]
    pypi.write_bytes(data)
    a, b = wheel_files(built), wheel_files(pypi)
    # RECORD hashes and WHEEL's Generator line name the build tool, not the code.
    tool_files = {f"ha_mcp-{version}.dist-info/{n}" for n in ("RECORD", "WHEEL")}
    diff = sorted(n for n in a.keys() | b.keys() if n not in tool_files and a.get(n) != b.get(n))
    if diff:
        sys.exit("Built wheel differs from PyPI's:\n  " + "\n  ".join(diff[:40]))
    print(f"PyPI wheel {wheel['filename']} matches the tag build ({len(a)} files)")
    return built, digest, hashlib.sha256(built.read_bytes()).hexdigest()


def vendor(built: Path) -> None:
    VENDOR.mkdir()
    with zipfile.ZipFile(built) as zf:
        zf.extractall(VENDOR)
    (VENDOR / "README.md").write_text(
        "The ha-mcp server, unpacked from a wheel built from the upstream tag named in\n"
        "fork/UPSTREAM.json. Generated by fork/build.py; do not edit by hand.\n")


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name.split("[")[0].strip().lower())


def compile_pins(reqs: list[str], constraints: Path, work: Path, cutoff: str) -> dict[str, str]:
    infile, outfile = work / "in.txt", work / "out.txt"
    infile.write_text("\n".join(reqs) + "\n")
    run("uv", "pip", "compile", str(infile), "-o", str(outfile), "-q",
        "--python-version", PY_VERSION, "--python-platform", PLATFORM,
        "-c", str(constraints), "--no-header", "--no-annotate",
        "--exclude-newer", cutoff,
        "--exclude-newer-package", f"homeassistant={dt.datetime.now(dt.UTC):%Y-%m-%dT%H:%M:%SZ}")
    pins = {}
    for line in outfile.read_text().splitlines():
        m = re.match(r"([A-Za-z0-9_.\-\[\]]+)\s*==\s*(\S+)", line.strip())
        if m:
            pins[norm(m.group(1))] = (m.group(1), m.group(2))
    return pins


def pin_requirements(ha: str, wheel: Path, own: list[str], work: Path, cutoff: str) -> list[str]:
    constraints = work / "package_constraints.txt"
    constraints.write_bytes(fetch(
        f"https://raw.githubusercontent.com/home-assistant/core/{ha}/homeassistant/package_constraints.txt"))
    core = compile_pins([f"homeassistant=={ha}"], constraints, work, cutoff)
    full = compile_pins([f"homeassistant=={ha}", f"ha-mcp @ {wheel.as_uri()}", *own],
                        constraints, work, cutoff)
    moved = {k: (core[k][1], v[1]) for k, v in full.items() if k in core and core[k][1] != v[1]}
    if moved:
        sys.exit(f"ha-mcp would move packages Home Assistant {ha} ships: {moved}")
    pins = sorted(f"{name}=={ver}" for k, (name, ver) in full.items()
                  if k not in core and k != "ha-mcp")
    (FORK / "requirements.lock").write_text(
        f"# Exact pins for ha-mcp + ha_mcp_tools on Home Assistant {ha}\n"
        f"# (Python {PY_VERSION}, {PLATFORM}); packages Home Assistant ships are left to it.\n"
        f"# Nothing released after {cutoff}.\n"
        + "\n".join(pins) + "\n")
    return pins


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", required=True, help="upstream ha-mcp tag, e.g. v8.7.0")
    ap.add_argument("--ha", required=True, help="Home Assistant version to pin against")
    ap.add_argument("--rev", type=int, default=1, help="fork revision of this upstream tag")
    ap.add_argument("--zip", action="store_true", help="write dist/ha_mcp_tools.zip")
    ap.add_argument("--cooldown-days", type=int, default=7,
                    help="ignore dependency releases younger than this")
    ap.add_argument("--no-patches", action="store_true",
                    help="copy the component unpatched (for re-authoring a patch)")
    args = ap.parse_args()

    src = checkout(args.tag)
    version = args.tag.lstrip("v")
    commit = run("git", "rev-parse", "HEAD", cwd=src, capture=True).strip()
    skills = run("git", "rev-parse", "HEAD", cwd=src / "src/ha_mcp/resources/skills-vendor",
                 capture=True).strip()
    pristine = json.loads((src / "custom_components/ha_mcp_tools/manifest.json").read_text())

    cutoff = f"{dt.datetime.now(dt.UTC) - dt.timedelta(days=args.cooldown_days):%Y-%m-%dT%H:%M:%SZ}"
    copy_component(src, not args.no_patches)
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        built, pypi_sha, built_sha = build_and_compare(src, version, work)
        vendor(built)
        pins = pin_requirements(args.ha, built, pristine["requirements"], work, cutoff)

    manifest_path = COMPONENT / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    manifest["requirements"] = pins
    manifest["version"] = f"{pristine['version']}.{args.rev}"
    manifest_path.write_text(json.dumps(manifest, indent=4) + "\n")

    upstream = {
        "upstream_repo": UPSTREAM_GIT,
        "tag": args.tag,
        "commit": commit,
        "skills_submodule_commit": skills,
        "component_version": pristine["version"],
        "fork_version": manifest["version"],
        "server_version": version,
        "pypi_wheel_sha256": pypi_sha,
        "built_wheel_sha256": built_sha,
        "home_assistant_pinned_against": args.ha,
        "dependencies_released_before": cutoff,
        "patches": [] if args.no_patches else
                   [p.name for p in sorted((FORK / "patches").glob("*.patch"))],
    }
    (FORK / "UPSTREAM.json").write_text(json.dumps(upstream, indent=2) + "\n")
    print(json.dumps(upstream, indent=2))

    if args.zip:
        dist = ROOT / "dist"
        dist.mkdir(exist_ok=True)
        out = dist / "ha_mcp_tools.zip"
        with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zf:
            for path in sorted(COMPONENT.rglob("*")):
                if path.is_file() and "__pycache__" not in path.parts:
                    info = zipfile.ZipInfo(str(path.relative_to(COMPONENT)), (1980, 1, 1, 0, 0, 0))
                    info.compress_type = zipfile.ZIP_DEFLATED
                    info.external_attr = 0o644 << 16
                    zf.writestr(info, path.read_bytes())
        print(f"{out} sha256 {hashlib.sha256(out.read_bytes()).hexdigest()}")


if __name__ == "__main__":
    main()
